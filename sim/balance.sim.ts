import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { BALANCE } from '../src/content/balance';
import { BONUS_CARD_IDS, CARDS, FIGHTERS, getCard } from '../src/content/cards';
import { SIM_PROFILE, type AiProfile } from '../src/engine/ai';
import { runMatch } from '../src/engine/match';
import { Rng } from '../src/engine/rng';

/*
 * Round robin between every pair of fighters (both seat orders), AI vs AI.
 *   MATCHES=n  matches per ordered pair (default 40)
 *   BONUS=n    each side brings n random bonus cards (default 0)
 *   SEED=n     base seed (default 1)
 *   ARENA=id   arena (default classic)
 * Try changes without editing content (the report then goes to sim/, not docs/):
 *   RULES="fatigueAfterRound=8"                       numbers in BALANCE
 *   CARD="umbraClaw.damage=20;vexHex.cost=-10"        card fields (patterns as 010/111/010)
 *   FIGHTER="umbra.passive.mods.vsMovedBonus=5"       fighter fields, by path
 */
const MATCHES = Number(process.env.MATCHES ?? 40);
const BONUS = Number(process.env.BONUS ?? 0);
const SEED = Number(process.env.SEED ?? 1);
const ARENA = process.env.ARENA ?? 'classic';
/** WEIGHTS="trap=0.2,ammo=0" tries other CPU scoring weights (the report is then not written to docs/). */
const WEIGHTS = process.env.WEIGHTS ?? '';
const PROFILE: AiProfile = WEIGHTS
  ? { ...SIM_PROFILE, weights: { ...SIM_PROFILE.weights, ...Object.fromEntries(WEIGHTS.split(',').map((kv) => [kv.split('=')[0], Number(kv.split('=')[1])])) } }
  : SIM_PROFILE;

const RULES = process.env.RULES ?? '';
const CARD = process.env.CARD ?? '';
const FIGHTER = process.env.FIGHTER ?? '';
/** Set `obj.a.b.c = value` from "a.b.c=value" (numbers stay numbers; "x/y/z" becomes an array). */
function setPath(root: Record<string, unknown>, spec: string): void {
  const [path, raw] = spec.split('=');
  const keys = path.trim().split('.');
  let o = root;
  for (const k of keys.slice(0, -1)) o = (o[k] ??= {}) as Record<string, unknown>;
  const n = Number(raw);
  o[keys[keys.length - 1]] = raw.includes('/') ? raw.split('/') : raw === 'true' || raw === 'false' ? raw === 'true' : Number.isNaN(n) ? raw : n;
}
for (const kv of RULES.split(/[;,]/).filter(Boolean)) setPath(BALANCE as unknown as Record<string, unknown>, kv);
for (const kv of CARD.split(';').filter(Boolean)) setPath(CARDS as unknown as Record<string, unknown>, kv);
const byId = Object.fromEntries(FIGHTERS.map((f) => [f.id, f]));
for (const kv of FIGHTER.split(';').filter(Boolean)) setPath(byId as unknown as Record<string, unknown>, kv);

const pct = (n: number, d: number) => (d ? `${Math.round((100 * n) / d)}%` : '–');

it('balance report', () => {
  const ids = FIGHTERS.map((f) => f.id);
  const name = (id: string) => FIGHTERS.find((f) => f.id === id)!.name;
  const wins: Record<string, Record<string, number>> = {};
  const games: Record<string, Record<string, number>> = {};
  for (const a of ids) {
    wins[a] = {};
    games[a] = {};
    for (const b of ids) wins[a][b] = games[a][b] = 0;
  }
  const cards: Record<string, { plays: number; matches: number; won: number }> = {};
  let total = 0, rounds = 0, draws = 0, timeouts = 0, seat0Wins = 0;
  const started = Date.now();
  const rng = new Rng(SEED);

  for (const a of ids) {
    for (const b of ids) {
      if (a === b) continue;
      for (let k = 0; k < MATCHES; k++) {
        const bonus = () => (BONUS ? rng.shuffle([...BONUS_CARD_IDS]).slice(0, BONUS) : []);
        const rec = runMatch(
          { fighterId: a, bonusCards: bonus() },
          { fighterId: b, bonusCards: bonus() },
          { profiles: [PROFILE, PROFILE], seed: rng.int(2 ** 31), arenaId: ARENA },
        );
        total++;
        rounds += rec.rounds;
        games[a][b]++;
        games[b][a]++;
        const w = rec.outcome.winner;
        if (w === null) {
          draws++;
          wins[a][b] += 0.5;
          wins[b][a] += 0.5;
        }
        if (rec.timedOut) timeouts++;
        if (w === 0) {
          wins[a][b]++;
          seat0Wins++;
        } else if (w === 1) wins[b][a]++;

        for (const seat of [0, 1] as const) {
          const played = new Set<string>();
          for (const h of rec.history) for (const id of h.plans[seat]) {
            played.add(id);
            (cards[id] ??= { plays: 0, matches: 0, won: 0 }).plays++;
          }
          for (const id of played) {
            cards[id].matches++;
            if (w === seat) cards[id].won++;
          }
        }
      }
    }
  }

  const overall = ids.map((a) => {
    const w = ids.reduce((s, b) => s + wins[a][b], 0);
    const g = ids.reduce((s, b) => s + games[a][b], 0);
    return { a, w, g };
  });
  const lines: string[] = [];
  lines.push('# Balance report', '');
  lines.push(
    `Generated by \`npm run balance\` (${MATCHES} matches per ordered pair, ${BONUS} bonus cards each, arena ${ARENA}, seed ${SEED}). ` +
      `AI vs AI with the simulation profile, so these numbers describe the cards, not human play.`,
    '',
  );
  if (RULES || CARD || FIGHTER) lines.push(`Changes tried: ${[RULES, CARD, FIGHTER].filter(Boolean).join(' · ')}`, '');
  lines.push(`- Matches: ${total} · average length ${(rounds / total).toFixed(1)} rounds · draws ${pct(draws, total)} · hit round limit ${timeouts}`);
  lines.push(`- Player 1 (left start) wins ${pct(seat0Wins, total - draws)} of decided matches`);
  lines.push(`- Time: ${((Date.now() - started) / 1000).toFixed(0)} s`, '');
  lines.push('## Overall score', '', 'Wins count 1 and draws count ½, so an even fighter scores 50%.', '', '| Fighter | Score | Matches |', '|---|---|---|');
  for (const o of [...overall].sort((x, y) => y.w / y.g - x.w / x.g)) lines.push(`| ${name(o.a)} | ${pct(o.w, o.g)} | ${o.g} |`);
  lines.push('', '## Matchups (row fighter’s score)', '');
  lines.push(`| | ${ids.map(name).join(' | ')} |`, `|---|${ids.map(() => '---').join('|')}|`);
  for (const a of ids) lines.push(`| **${name(a)}** | ${ids.map((b) => (a === b ? '–' : pct(wins[a][b], games[a][b]))).join(' | ')} |`);
  lines.push('', '## Cards', '', 'Plays per match = how often the card is used when it is in the deck. Win rate = matches won when the card was played at least once.', '');
  lines.push('| Card | Owner | Plays per match | Win rate when played |', '|---|---|---|---|');
  const owner = (id: string) => FIGHTERS.find((f) => f.signature.includes(id))?.name ?? (getCard(id).bonus ? 'bonus' : 'basic');
  const deckMatches = (id: string) => {
    const f = FIGHTERS.find((x) => x.signature.includes(id));
    if (!f) return total * 2;
    return ids.reduce((s, b) => s + games[f.id][b], 0);
  };
  for (const [id, c] of Object.entries(cards).sort((x, y) => owner(x[0]).localeCompare(owner(y[0])))) {
    const denom = getCard(id).bonus ? c.matches : deckMatches(id);
    lines.push(`| ${getCard(id).name} | ${owner(id)} | ${(c.plays / Math.max(1, denom)).toFixed(2)} | ${pct(c.won, c.matches)} |`);
  }
  const report = lines.join('\n') + '\n';
  // Only the default run (Classic, no bonus cards) updates docs/BALANCE.md; other runs write next to it.
  const tag = process.env.TAG ? `-${process.env.TAG}` : '';
  const file =
    ARENA === 'classic' && !BONUS && !WEIGHTS && !tag && !RULES && !CARD && !FIGHTER
      ? '../docs/BALANCE.md'
      : `../sim/balance-${ARENA}${BONUS ? `-bonus${BONUS}` : ''}${WEIGHTS ? '-weights' : ''}${tag}.md`;
  writeFileSync(new URL(file, import.meta.url), report);
  console.log(report);
});
